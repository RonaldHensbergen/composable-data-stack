#!/usr/bin/env python3
"""Publish contract coverage: how much of the system the Contract covers with
executable tests.

The Contract is the written-down description of what the platform must do:
the JSON Schemas in cli/resources/ (enforced for every module and profile by
tests/test_module_contract_schema.py), the `contracts:` blocks in each
module.yaml, and the shared contract definitions in shared/contracts/.

This script measures how much of that surface is exercised by tests in
tests/: a module, profile, or shared contract counts as covered when at least
one test file names it — either in the test file's own name or as a
path/name reference in the test body. The percentage is published in
docs/contract-coverage.md so everyone can see how much of the system the
Contract still leaves unwritten.

Used by .github/workflows/contract-coverage.yml (fails CI on drift via
--check; files a weekly report issue otherwise) and runnable locally:

    python scripts/check_contract_coverage.py          # regenerate the report
    python scripts/check_contract_coverage.py --check  # exit 1 if stale
    python scripts/check_contract_coverage.py --stdout # print, do not write
"""
from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
REPORT_PATH = REPO_ROOT / "docs" / "contract-coverage.md"
MODULE_ROOTS = ("modules", "modules-experimental")
PROFILES_ROOT = "profiles"
CONTRACTS_ROOT = "shared/contracts"
TESTS_ROOT = "tests"

HEADER = """\
# Contract Coverage

<!-- Generated by scripts/check_contract_coverage.py — do not edit by hand.
     Regenerate with `make contract-coverage`. CI runs the script with
     `--check` and fails when this file is stale. -->

The Contract is the written-down description of what the platform must do:
the JSON Schemas in `cli/resources/` (enforced for every module and profile
by `tests/test_module_contract_schema.py`), the `contracts:` blocks in each
`module.yaml`, and the shared contract definitions in `shared/contracts/`.

This page publishes how much of that Contract is covered by executable tests
in `tests/`. A module, profile, or shared contract counts as covered when at
least one test file names it — in the test file's own name, or as a path or
name reference in the test body. Reaching 100% is hard; the number tells
everyone how much of the system is still unwritten.
"""


@dataclass(frozen=True)
class Item:
    """One contractable unit: a module, a profile, or a shared contract."""

    rel_path: str
    name: str
    covered: bool


def _norm(text: str) -> str:
    return text.lower().replace("-", "_")


def _load_tests() -> tuple[list[str], list[str]]:
    """Return (normalized test file names, test file bodies)."""
    test_dir = REPO_ROOT / TESTS_ROOT
    files = sorted(test_dir.glob("test_*.py"))
    names = [_norm(p.name) for p in files]
    bodies = [p.read_text(encoding="utf-8", errors="replace") for p in files]
    return names, bodies


def _is_covered(rel_path: str, name: str, test_names: list[str], test_bodies: list[str]) -> bool:
    normalized = _norm(name)
    if any(normalized in test_name for test_name in test_names):
        return True
    if any(rel_path in body for body in test_bodies):
        return True
    # Name referenced in a test body, bounded so that e.g. the profile
    # "local-dagster-postgres-superset" is not covered merely by a reference
    # to "local-dagster-postgres-superset-dbt".
    pattern = re.compile(r"(?<![a-z0-9_])" + re.escape(normalized) + r"(?![a-z0-9_])")
    return any(pattern.search(_norm(body)) for body in test_bodies)


def _collect() -> dict[str, list[Item]]:
    test_names, test_bodies = _load_tests()
    sections: dict[str, list[Item]] = {}

    modules: list[Item] = []
    for root_name in MODULE_ROOTS:
        for module_yaml in sorted((REPO_ROOT / root_name).rglob("module.yaml")):
            doc = yaml.safe_load(module_yaml.read_text(encoding="utf-8")) or {}
            name = str(doc.get("metadata", {}).get("name") or module_yaml.parent.name)
            rel = str(module_yaml.parent.relative_to(REPO_ROOT))
            modules.append(Item(rel, name, _is_covered(rel, name, test_names, test_bodies)))
    sections["Modules"] = modules

    profiles: list[Item] = []
    for profile_yaml in sorted((REPO_ROOT / PROFILES_ROOT).rglob("profile.yaml")):
        doc = yaml.safe_load(profile_yaml.read_text(encoding="utf-8")) or {}
        name = str(doc.get("metadata", {}).get("name") or profile_yaml.parent.name)
        rel = str(profile_yaml.parent.relative_to(REPO_ROOT))
        profiles.append(Item(rel, name, _is_covered(rel, name, test_names, test_bodies)))
    sections["Profiles"] = profiles

    contracts: list[Item] = []
    contracts_dir = REPO_ROOT / CONTRACTS_ROOT
    glob_covered = any(CONTRACTS_ROOT in body for body in test_bodies)
    for contract_yaml in sorted(contracts_dir.glob("*.yaml")):
        rel = str(contract_yaml.relative_to(REPO_ROOT))
        contracts.append(
            Item(rel, contract_yaml.stem, glob_covered or _is_covered(rel, contract_yaml.stem, test_names, test_bodies))
        )
    sections["Shared contracts"] = contracts

    return sections


def _render(sections: dict[str, list[Item]]) -> str:
    lines: list[str] = [HEADER.rstrip("\n"), ""]

    all_items = [item for items in sections.values() for item in items]
    total = len(all_items)
    covered = sum(1 for item in all_items if item.covered)
    pct = round(100 * covered / total) if total else 0
    summary_parts = [
        f"{title.lower()} {sum(1 for i in items if i.covered)}/{len(items)}"
        f" ({round(100 * sum(1 for i in items if i.covered) / len(items)) if items else 0}%)"
        for title, items in sections.items()
    ]
    lines.append(f"**Overall contract coverage: {covered} of {total} ({pct}%)** — " + ", ".join(summary_parts))
    lines.append("")

    for title, items in sections.items():
        lines.append(f"## {title}")
        lines.append("")
        lines.append("| Path | Name | Covered by tests |")
        lines.append("| --- | --- | --- |")
        for item in items:
            lines.append(f"| `{item.rel_path}` | {item.name} | {'yes' if item.covered else '**no**'} |")
        lines.append("")

    lines.append(
        "To cover an item, add a test in `tests/` that names it (e.g. "
        "`test_<name>_*.py` or a reference to its repo-relative path) and "
        "exercises its contract behavior.\n"
    )
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if docs/contract-coverage.md is missing or stale")
    parser.add_argument("--stdout", action="store_true", help="print the report instead of writing it")
    args = parser.parse_args(argv)

    report = _render(_collect())

    if args.stdout:
        print(report)
        return 0

    if args.check:
        current = REPORT_PATH.read_text(encoding="utf-8") if REPORT_PATH.exists() else ""
        if current != report:
            print(f"{REPORT_PATH.relative_to(REPO_ROOT)} is stale. Regenerate with `make contract-coverage`.", file=sys.stderr)
            return 1
        print(f"{REPORT_PATH.relative_to(REPO_ROOT)} is up to date")
        return 0

    REPORT_PATH.write_text(report, encoding="utf-8")
    print(f"Wrote {REPORT_PATH.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
